#!/usr/bin/env python3
"""Renders the map marker images (brand badges, machine, generic store, "you are here").

Map text depends on the style's glyph server, so markers are plain images instead.
Run after editing src/lib/brands.json:  python3 scripts/generate-map-icons.py
Writes assets/map/*.png and src/lib/mapIcons.ts.
"""
import json
import math
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "map")
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZE = 96  # drawn at 4x and downsampled for smooth edges
SS = 4


def canvas():
    img = Image.new("RGBA", (SIZE * SS, SIZE * SS), (0, 0, 0, 0))
    return img, ImageDraw.Draw(img)


def disc(draw, color, inset=0, outline=None, width=0):
    s = SIZE * SS
    pad = inset * SS
    draw.ellipse((pad, pad, s - pad, s - pad), fill=color, outline=outline, width=width * SS)


def text(draw, label, color):
    s = SIZE * SS
    size = {1: 52, 2: 40}.get(len(label), 30) * SS
    font = ImageFont.truetype(FONT, size)
    l, t, r, b = draw.textbbox((0, 0), label, font=font)
    draw.text(((s - (r - l)) / 2 - l, (s - (b - t)) / 2 - t), label, font=font, fill=color)


def save(img, name):
    img.resize((SIZE, SIZE), Image.LANCZOS).save(os.path.join(OUT, f"{name}.png"), optimize=True)


def badge(label, color, text_color):
    img, d = canvas()
    disc(d, "#FFFFFF", inset=2)
    disc(d, color, inset=8)
    text(d, label, text_color)
    return img


def store_icon():
    img, d = canvas()
    disc(d, "#FFFFFF", inset=2)
    disc(d, "#5B6B73", inset=8)
    s = SS
    # simple shop: awning + body
    d.rectangle((30 * s, 46 * s, 66 * s, 70 * s), fill="#FFFFFF")
    d.polygon([(26 * s, 46 * s), (34 * s, 28 * s), (62 * s, 28 * s), (70 * s, 46 * s)], fill="#FFFFFF")
    d.rectangle((43 * s, 54 * s, 53 * s, 70 * s), fill="#5B6B73")
    return img


def machine_icon():
    img, d = canvas()
    disc(d, "#FFFFFF", inset=2)
    disc(d, "#1F7A4D", inset=8)
    s = SS
    # reverse vending machine: cabinet with a round bottle slot
    d.rounded_rectangle((32 * s, 24 * s, 64 * s, 72 * s), radius=4 * s, fill="#FFFFFF")
    d.ellipse((40 * s, 32 * s, 56 * s, 48 * s), fill="#1F7A4D")
    d.rectangle((38 * s, 56 * s, 58 * s, 60 * s), fill="#1F7A4D")
    return img


def person_icon():
    img, d = canvas()
    s = SIZE * SS
    disc(d, (37, 128, 255, 70), inset=0)  # halo
    disc(d, "#FFFFFF", inset=14)
    disc(d, "#2580FF", inset=20)
    k = SS
    # walking figure
    d.ellipse((43 * k, 30 * k, 53 * k, 40 * k), fill="#FFFFFF")
    w = 5 * k
    d.line([(48 * k, 41 * k), (46 * k, 56 * k)], fill="#FFFFFF", width=w)  # body
    d.line([(46 * k, 56 * k), (40 * k, 68 * k)], fill="#FFFFFF", width=w)  # back leg
    d.line([(46 * k, 56 * k), (54 * k, 67 * k)], fill="#FFFFFF", width=w)  # front leg
    d.line([(39 * k, 50 * k), (48 * k, 44 * k), (56 * k, 51 * k)], fill="#FFFFFF", width=w)  # arms
    return img


def main():
    os.makedirs(OUT, exist_ok=True)
    brands = json.load(open(os.path.join(ROOT, "src", "lib", "brands.json"), encoding="utf-8"))
    icons = {}
    for b in brands:
        name = f"brand-{b['id']}"
        if name not in icons:
            save(badge(b["label"], b["color"], b["textColor"]), name)
            icons[name] = name
    for name, fn in (("store", store_icon), ("machine", machine_icon), ("me", person_icon)):
        save(fn(), name)
        icons[name] = name

    lines = [
        "// Generated by scripts/generate-map-icons.py, do not edit.",
        "export const MAP_ICONS = {",
        *[f"  '{k}': require('@/assets/map/{v}.png')," for k, v in sorted(icons.items())],
        "};",
        "",
    ]
    with open(os.path.join(ROOT, "src", "lib", "mapIcons.ts"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"{len(icons)} icons")


if __name__ == "__main__":
    main()
